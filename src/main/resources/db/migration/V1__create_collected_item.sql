CREATE TABLE collected_item (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source VARCHAR(40) NOT NULL,
    external_id VARCHAR(2000) NOT NULL,
    title VARCHAR(1000),
    link VARCHAR(2000) NOT NULL,
    published_at TIMESTAMP WITH TIME ZONE,
    collected_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uk_collected_item_source_external UNIQUE (source, external_id)
);
CREATE INDEX idx_collected_item_collected_at ON collected_item (collected_at);
