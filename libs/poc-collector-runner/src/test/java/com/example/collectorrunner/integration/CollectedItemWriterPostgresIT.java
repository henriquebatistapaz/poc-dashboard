package com.example.collectorrunner.integration;

import java.sql.SQLException;
import java.time.Clock;
import java.time.Instant;
import java.time.ZoneOffset;
import java.util.List;
import java.util.concurrent.Callable;
import java.util.concurrent.Executors;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.postgresql.ds.PGSimpleDataSource;
import org.testcontainers.containers.PostgreSQLContainer;
import org.testcontainers.junit.jupiter.Container;
import org.testcontainers.junit.jupiter.Testcontainers;
import static org.junit.jupiter.api.Assertions.*;

@Testcontainers
class CollectedItemWriterPostgresIT {
    @Container static final PostgreSQLContainer<?> POSTGRES = new PostgreSQLContainer<>("postgres:18-alpine");
    private PGSimpleDataSource dataSource;
    private CollectedItemWriter writer;
    private final Instant now = Instant.parse("2026-11-06T12:00:00Z");

    @BeforeEach
    void setup() throws Exception {
        dataSource = new PGSimpleDataSource();
        dataSource.setURL(POSTGRES.getJdbcUrl());
        dataSource.setUser(POSTGRES.getUsername());
        dataSource.setPassword(POSTGRES.getPassword());
        writer = new CollectedItemWriter(dataSource, Clock.fixed(now, ZoneOffset.UTC));
        try (var connection = dataSource.getConnection(); var statement = connection.createStatement()) {
            statement.execute("DROP TABLE IF EXISTS collected_item");
            // Consumer-owned schema fixture. Dashboard integration tests verify its actual Flyway migration.
            statement.execute("""
                CREATE TABLE collected_item (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    source VARCHAR(40) NOT NULL, external_id VARCHAR(2000) NOT NULL,
                    title VARCHAR(1000), link VARCHAR(2000) NOT NULL,
                    published_at TIMESTAMP WITH TIME ZONE, collected_at TIMESTAMP WITH TIME ZONE NOT NULL,
                    UNIQUE (source, external_id))
                """);
        }
    }

    @Test
    void deduplicatesAcrossBatchesAndPreservesFirstContent() throws Exception {
        var item = new CollectedItemInput("demo", "1", "original", "https://example.org/1", null);
        assertEquals(new CollectedItemWriter.WriteResult(1, 1), writer.write(List.of(item, item)));
        var changed = new CollectedItemInput("demo", "1", "changed", "https://example.org/2", now);
        assertEquals(new CollectedItemWriter.WriteResult(0, 1), new CollectedItemWriter(dataSource).write(List.of(changed)));
        assertEquals(1, writer.write(List.of(new CollectedItemInput("other", "1", null, "https://example.org/1", now))).inserted());
        try (var connection = dataSource.getConnection(); var statement = connection.createStatement();
             var rows = statement.executeQuery("SELECT * FROM collected_item WHERE source = 'demo'")) {
            assertTrue(rows.next());
            assertEquals("original", rows.getString("title"));
            assertNull(rows.getTimestamp("published_at"));
            assertEquals(now, rows.getTimestamp("collected_at").toInstant());
        }
    }

    @Test
    void concurrentWritersInsertOnlyOneRow() throws Exception {
        var item = new CollectedItemInput("demo", "race", "race", "https://example.org/race", now);
        try (var executor = Executors.newFixedThreadPool(4)) {
            Callable<Integer> task = () -> writer.write(List.of(item)).inserted();
            var results = executor.invokeAll(List.of(task, task, task, task));
            int inserted = 0;
            for (var result : results) inserted += result.get();
            assertEquals(1, inserted);
        }
    }

    @Test
    void rollsBackWholeBatchWhenDatabaseRejectsAnItem() throws Exception {
        var valid = new CollectedItemInput("demo", "1", "valid", "https://example.org/1", null);
        var invalid = new CollectedItemInput("demo", "2", "invalid\0text", "https://example.org/2", null);
        assertThrows(SQLException.class, () -> writer.write(List.of(valid, invalid)));
        try (var connection = dataSource.getConnection(); var statement = connection.createStatement();
             var rows = statement.executeQuery("SELECT count(*) FROM collected_item")) {
            assertTrue(rows.next());
            assertEquals(0, rows.getInt(1));
        }
        assertEquals(1, writer.write(List.of(valid)).inserted());
    }

    @Test
    void handlesEmptyAndRejectsUnboundedBatch() throws Exception {
        assertEquals(new CollectedItemWriter.WriteResult(0, 0), writer.write(List.of()));
        assertThrows(IllegalArgumentException.class, () -> writer.write(null));
        var item = new CollectedItemInput("demo", "1", null, "https://example.org/1", null);
        assertThrows(IllegalArgumentException.class, () -> writer.write(java.util.Collections.nCopies(1001, item)));
    }
}
